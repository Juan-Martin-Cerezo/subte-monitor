import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const ZIP = path.join(ROOT, "gtfs.zip");
const OUT = path.join(ROOT, "src/lib/anden/station-names.ts");
const ROUTES = [
  "LineaA",
  "LineaB",
  "LineaC",
  "LineaD",
  "LineaE",
  "LineaH",
  "PM-Civico",
  "PM-Savio",
];

function parseCsv(raw: string): Record<string, string>[] {
  const text = raw.startsWith("\uFEFF") ? raw.slice(1) : raw;
  const lines = text.split(/\r?\n/).filter((line) => line.trim());
  if (!lines.length) return [];

  const split = (line: string) => {
    const cells: string[] = [];
    let current = "";
    let quoted = false;
    for (let i = 0; i < line.length; i += 1) {
      const char = line[i];
      if (char === '"') quoted = !quoted;
      else if (char === "," && !quoted) {
        cells.push(current.trim());
        current = "";
      } else current += char;
    }
    cells.push(current.trim());
    return cells;
  };

  const headers = split(lines[0]);
  return lines.slice(1).map((line) => {
    const cells = split(line);
    return Object.fromEntries(headers.map((header, index) => [header, cells[index] ?? ""]));
  });
}

function read(file: string): Record<string, string>[] {
  return parseCsv(
    execSync(`unzip -p "${ZIP}" ${file}`, { encoding: "utf8", maxBuffer: 20 * 1024 * 1024 })
  );
}

const trips = read("trips.txt");
const stopTimes = read("stop_times.txt");
const stops = read("stops.txt");

const byRoute: Record<string, string[]> = {};
for (const trip of trips) {
  const key = `${trip.route_id}_${trip.direction_id}`;
  (byRoute[key] ??= []).push(trip.trip_id);
}

const timesByTrip: Record<string, Record<string, string>[]> = {};
for (const time of stopTimes) (timesByTrip[time.trip_id] ??= []).push(time);

const names = new Map<string, string>();
for (const route of ROUTES) {
  for (const direction of ["0", "1"]) {
    const tripIds = byRoute[`${route}_${direction}`] ?? [];
    let best: Record<string, string>[] = [];
    for (const tripId of tripIds) {
      const list = timesByTrip[tripId] ?? [];
      if (list.length > best.length) best = list;
    }
    for (const time of best) {
      const stop = stops.find((candidate) => candidate.stop_id === time.stop_id);
      if (!stop?.stop_name) continue;
      const normalized = stop.stop_name
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase();
      names.set(normalized, stop.stop_name);
    }
  }
}

const ordered = [...names.values()].sort((a, b) => a.localeCompare(b, "es"));
const body = ordered.map((name) => `  ${JSON.stringify(name)},`).join("\n");

writeFileSync(
  OUT,
  `// generated by scripts/anden/build-stations.ts from gtfs.zip\nexport const STATION_NAMES: string[] = [\n${body}\n];\n`
);

console.log(`${ordered.length} stations written to ${path.relative(ROOT, OUT)}`);
